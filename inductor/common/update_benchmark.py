#!/usr/bin/env python3
"""
Scan inductor/<N>/ runs and regenerate inductor/BENCHMARK.md
(summary leaderboard + per-run detail).

  python3 inductor/common/update_benchmark.py
  python3 inductor/common/update_benchmark.py --root inductor
"""
from __future__ import annotations

import argparse
import json
import re
from datetime import datetime, timezone
from pathlib import Path

import yaml


def check_status(log_path: Path, pass_token: str) -> str:
    if not log_path.is_file():
        return "—"
    text = log_path.read_text(errors="replace")
    if pass_token in text:
        return "PASS"
    if "FAIL" in text:
        return "FAIL"
    return "?"


def load_run(run_dir: Path) -> dict | None:
    if not run_dir.is_dir() or not run_dir.name.isdigit():
        return None
    cfg_path = run_dir / "config.yaml"
    if not cfg_path.is_file():
        return None
    cfg = yaml.safe_load(cfg_path.read_text()) or {}
    summary = {}
    sj = run_dir / "sim" / "summary.json"
    if sj.is_file():
        summary = json.loads(sj.read_text())
    status_em = "—"
    st = run_dir / "sim" / "STATUS.txt"
    if st.is_file():
        head = st.read_text(errors="replace").splitlines()[0].strip()
        status_em = head
    return {
        "id": int(run_dir.name),
        "path": run_dir,
        "rel": f"{run_dir.name}",
        "cfg": cfg,
        "summary": summary,
        "drc": check_status(run_dir / "drc" / "inductor.log", "DRC PASS"),
        "lvs": check_status(run_dir / "lvs" / "inductor.log", "LVS PASS"),
        "shorts": check_status(run_dir / "lvs" / "shorts.log", "SHORTS PASS"),
        "em": status_em,
        "has_layout_png": (run_dir / "layout" / "inductor.png").is_file(),
        "has_perf_png": (run_dir / "sim" / "performance.png").is_file(),
        "has_result": (run_dir / "RESULT.md").is_file(),
    }


def fmt(v, prec=3, scale=1.0, suffix=""):
    if v is None:
        return "—"
    try:
        return f"{float(v) * scale:.{prec}f}{suffix}"
    except (TypeError, ValueError):
        return "—"


def champion(runs: list[dict], key: str, higher=True) -> str:
    scored = []
    for r in runs:
        v = r["summary"].get(key)
        if v is None:
            continue
        scored.append((float(v), r["id"], r["cfg"].get("name", "")))
    if not scored:
        return "—"
    scored.sort(key=lambda x: x[0], reverse=higher)
    v, i, name = scored[0]
    return f"**#{i}** `{name}` ({v:.3f})"


def render(runs: list[dict]) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []
    lines.append("# Inductor BENCHMARK")
    lines.append("")
    lines.append(
        f"Auto-generated by `inductor/common/update_benchmark.py` — **{len(runs)}** run(s) — {now}"
    )
    lines.append("")
    lines.append(
        "Regenerate: `python3 inductor/common/update_benchmark.py` "
        "or `./inductor/common/run_benchmark.sh`"
    )
    lines.append("")

    # ----- Summary -----
    lines.append("## Summary leaderboard")
    lines.append("")
    lines.append(
        "| Run | Name | Shape | Ports | Role | DRC | LVS | SHORTS | Engine | "
        "L₀ (nH) | L@f_ref (nH) | Q@f_ref | Q_max | SRF (GHz) | Links |"
    )
    lines.append(
        "|-----|------|-------|------:|------|-----|-----|--------|--------|"
        "--------:|-------------:|--------:|------:|----------:|-------|"
    )
    for r in sorted(runs, key=lambda x: x["id"]):
        c, s = r["cfg"], r["summary"]
        links = []
        if r["has_result"]:
            links.append(f"[RESULT]({r['rel']}/RESULT.md)")
        if r["has_layout_png"]:
            links.append(f"[layout]({r['rel']}/layout/inductor.png)")
        if r["has_perf_png"]:
            links.append(f"[EM]({r['rel']}/sim/performance.png)")
        lines.append(
            "| {id} | `{name}` | {shape} | {ports} | {role} | {drc} | {lvs} | {shorts} | {eng} | "
            "{L0} | {Lref} | {Qref} | {Qmax} | {srf} | {links} |".format(
                id=r["id"],
                name=c.get("name", ""),
                shape=c.get("shape", ""),
                ports=c.get("ports", ""),
                role=c.get("role", ""),
                drc=r["drc"],
                lvs=r["lvs"],
                shorts=r["shorts"],
                eng=s.get("engine", r["em"]),
                L0=fmt(s.get("L0_nH")),
                Lref=fmt(s.get("L_at_fref_nH")),
                Qref=fmt(s.get("Q_at_fref"), 2),
                Qmax=fmt(s.get("Q_max"), 2),
                srf=fmt(s.get("SRF_est_GHz"), 1),
                links=", ".join(links) if links else "—",
            )
        )
    lines.append("")

    lines.append("### Champions")
    lines.append("")
    lines.append(f"| Metric | Winner |")
    lines.append(f"|--------|--------|")
    lines.append(f"| Highest L₀ | {champion(runs, 'L0_nH', True)} |")
    lines.append(f"| Highest Q @ f_ref | {champion(runs, 'Q_at_fref', True)} |")
    lines.append(f"| Highest Q_max | {champion(runs, 'Q_max', True)} |")
    lines.append(f"| Highest SRF_est | {champion(runs, 'SRF_est_GHz', True)} |")
    lines.append("")

    # Pass rate
    n = len(runs)
    n_drc = sum(1 for r in runs if r["drc"] == "PASS")
    n_lvs = sum(1 for r in runs if r["lvs"] == "PASS")
    n_sh = sum(1 for r in runs if r["shorts"] == "PASS")
    n_em = sum(1 for r in runs if r["summary"])
    lines.append("### Gate status")
    lines.append("")
    lines.append(f"| Gate | Pass rate |")
    lines.append(f"|------|----------:|")
    lines.append(f"| DRC | {n_drc}/{n} |")
    lines.append(f"| LVS | {n_lvs}/{n} |")
    lines.append(f"| SHORTS | {n_sh}/{n} |")
    lines.append(f"| EM summary | {n_em}/{n} |")
    lines.append("")

    # Diversity matrix
    lines.append("### Design diversity")
    lines.append("")
    lines.append("| Run | (shape, ports, role) | W/S (µm) | turns | rin (µm) | t_metal (µm) |")
    lines.append("|-----|----------------------|---------:|------:|---------:|-------------:|")
    for r in sorted(runs, key=lambda x: x["id"]):
        c = r["cfg"]
        em = c.get("em") or {}
        lines.append(
            "| {id} | `({shape}, {ports}, {role})` | {w}/{s} | {t} | {rin} | {tm} |".format(
                id=r["id"],
                shape=c.get("shape"),
                ports=c.get("ports"),
                role=c.get("role"),
                w=c.get("width_um"),
                s=c.get("space_um"),
                t=c.get("turns"),
                rin=c.get("inner_radius_um"),
                tm=em.get("metal_thickness_um", "—"),
            )
        )
    lines.append("")

    # ----- Detail -----
    lines.append("## Detail by run")
    lines.append("")
    for r in sorted(runs, key=lambda x: x["id"]):
        c, s = r["cfg"], r["summary"]
        lines.append(f"### Run {r['id']} — `{c.get('name', '')}`")
        lines.append("")
        if r["has_layout_png"]:
            lines.append(f"![layout {r['id']}]({r['rel']}/layout/inductor.png)")
            lines.append("")
        if r["has_perf_png"]:
            lines.append(f"![EM {r['id']}]({r['rel']}/sim/performance.png)")
            lines.append("")
        lines.append("| Field | Value |")
        lines.append("|-------|-------|")
        lines.append(f"| Cell | `{c.get('cell', '')}` |")
        lines.append(f"| Shape / ports / role | {c.get('shape')} / {c.get('ports')} / {c.get('role')} |")
        lines.append(f"| Width / space | {c.get('width_um')} / {c.get('space_um')} µm |")
        lines.append(f"| Turns / rin | {c.get('turns')} / {c.get('inner_radius_um')} µm |")
        lines.append(f"| DRC / LVS / SHORTS | {r['drc']} / {r['lvs']} / {r['shorts']} |")
        lines.append(f"| EM engine | {s.get('engine', r['em'])} |")
        lines.append(f"| L₀ | {fmt(s.get('L0_nH'), 3, suffix=' nH')} |")
        lines.append(f"| L @ f_ref | {fmt(s.get('L_at_fref_nH'), 3, suffix=' nH')} |")
        lines.append(f"| Q @ f_ref | {fmt(s.get('Q_at_fref'), 2)} |")
        lines.append(f"| Q_max | {fmt(s.get('Q_max'), 2)} @ {fmt(s.get('f_at_Qmax_hz'), 2, scale=1e-9, suffix=' GHz')} |")
        lines.append(f"| C_ox | {fmt(s.get('C_fF'), 2, suffix=' fF')} |")
        lines.append(f"| SRF_est | {fmt(s.get('SRF_est_GHz'), 1, suffix=' GHz')} |")
        lines.append(f"| Segments / length | {s.get('n_segments', '—')} / {fmt(s.get('length_um'), 1, suffix=' µm')} |")
        lines.append(f"| RESULT | [{r['rel']}/RESULT.md]({r['rel']}/RESULT.md) |")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "*Do not edit this file by hand — it is overwritten by "
        "`update_benchmark.py` after each create-inductor run.*"
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--root",
        default=None,
        help="inductor/ directory (default: sibling of this script's parent)",
    )
    args = ap.parse_args()
    root = Path(args.root) if args.root else Path(__file__).resolve().parents[1]
    runs = []
    for p in sorted(root.iterdir(), key=lambda x: (not x.name.isdigit(), int(x.name) if x.name.isdigit() else 0)):
        r = load_run(p)
        if r:
            runs.append(r)
    out = root / "BENCHMARK.md"
    out.write_text(render(runs))
    print(f"Wrote {out} ({len(runs)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
