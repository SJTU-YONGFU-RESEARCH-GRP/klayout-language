#!/usr/bin/env bash
# Run Calibre LVS on nmos_demo.gds:
#   GOOD (NMOS_GOOD) expect CORRECT / PASS
#   BAD  (NMOS_BAD)  expect INCORRECT / FAIL (S–D metal short)
# Does not generate GDS — run ./generate_layout.sh first.
#
# Usage:
#   ./run_calibre_lvs.sh              # GOOD + BAD
#   ./run_calibre_lvs.sh --good
#   ./run_calibre_lvs.sh --bad
#   ./run_calibre_lvs.sh --lvs-only   # same as default (compat alias)
#   ./run_calibre_lvs.sh --gen-only   # alias → ./generate_layout.sh
#   ./run_calibre_lvs.sh --setup-help
#
# Env (same as drc/):
#   cp ../drc/calibre.env.example calibre.env   # or symlink ../drc/calibre.env
#   MGC_HOME / MGLS_LICENSE_FILE / CALIBRE

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GDS="${ROOT}/nmos_demo.gds"
GEN_SH="${ROOT}/generate_layout.sh"
RULES="${ROOT}/transistor.calibre.svrf"
CIR="${ROOT}/nmos.cir"
ENV_FILE="${ROOT}/calibre.env"
ENV_DRC="${ROOT}/../drc/calibre.env"
ENV_EXAMPLE="${ROOT}/../drc/calibre.env.example"
WORK="${ROOT}/.calibre_lvs_run"

WHICH="both"
SETUP_HELP=0

load_calibre_env() {
  if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    echo "==> Loaded ${ENV_FILE}"
  elif [[ -f "$ENV_DRC" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_DRC"
    echo "==> Loaded ${ENV_DRC}"
  fi
  # Prefer system python over Calibre's bin/python3 on PATH
  export PATH="/usr/bin:/bin:${MGC_HOME:+$MGC_HOME/bin:}${PATH}"
}

print_calibre_setup() {
  cat <<EOF
Calibre is not on PATH. Set it up like the DRC demo:

  cp ${ENV_EXAMPLE} ${ENV_FILE}
  \$EDITOR ${ENV_FILE}          # set MGC_HOME + MGLS_LICENSE_FILE
  ./run_calibre_lvs.sh

Or reuse the DRC env:
  ln -sf ../drc/calibre.env ${ENV_FILE}
  ./run_calibre_lvs.sh

Verify:
  \$MGC_HOME/bin/calibre -version
EOF
}

find_calibre() {
  if [[ -n "${CALIBRE:-}" && -x "${CALIBRE}" ]]; then
    printf '%s\n' "${CALIBRE}"
    return 0
  fi
  if command -v calibre >/dev/null 2>&1; then
    command -v calibre
    return 0
  fi
  local c
  for c in \
    "${MGC_HOME:-}/bin/calibre" \
    /opt/mentor/calibre/bin/calibre \
    /usr/local/mentor/calibre/bin/calibre
  do
    [[ -x "$c" ]] && { printf '%s\n' "$c"; return 0; }
  done
  return 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --good) WHICH="good" ;;
    --bad) WHICH="bad" ;;
    --lvs-only) ;; # default is check-only
    --gen-only)
      exec "$GEN_SH"
      ;;
    --setup-help) SETUP_HELP=1 ;;
    -h|--help)
      sed -n '2,20p' "$0"
      exit 0
      ;;
    *) echo "Unknown option: $1 (try --setup-help)" >&2; exit 1 ;;
  esac
  shift
done

if [[ "$SETUP_HELP" -eq 1 ]]; then
  print_calibre_setup
  exit 0
fi

load_calibre_env

CALIBRE_BIN="$(find_calibre)" || {
  echo "ERROR: calibre not found." >&2
  print_calibre_setup >&2
  exit 1
}

[[ -f "$GDS" ]] || {
  echo "ERROR: missing ${GDS}" >&2
  echo "Run:  ./generate_layout.sh" >&2
  exit 1
}
[[ -f "$CIR" ]] || { echo "ERROR: missing ${CIR}" >&2; exit 1; }
[[ -f "$RULES" ]] || { echo "ERROR: missing ${RULES}" >&2; exit 1; }

echo "==> Calibre: $("$CALIBRE_BIN" -version 2>/dev/null | head -1 || echo "$CALIBRE_BIN")"
echo "==> License: ${MGLS_LICENSE_FILE:-unset}"

mkdir -p "$WORK"

# Returns 0 if result matches expect (pass|fail), else 1
run_one() {
  local cell="$1"
  local tag="$2"
  local expect="$3"   # pass | fail
  local cell_work="${WORK}/${tag}"
  local report="${ROOT}/calibre_lvs_${tag}.txt"
  local lvsrep="${ROOT}/calibre_lvs_${tag}.rep"
  local log="${ROOT}/calibre_lvs_${tag}.log"
  local spice="${ROOT}/calibre_lvs_${tag}.sp"

  rm -rf "$cell_work"
  mkdir -p "$cell_work"
  local run_svrf="${cell_work}/run.svrf"
  local netlist="${cell_work}/layout.sp"
  local rep_work="${cell_work}/lvs.rep"

  cat >"$run_svrf" <<EOF
// Auto-generated by run_calibre_lvs.sh — do not edit
LAYOUT PATH "${GDS}"
LAYOUT PRIMARY "${cell}"
LAYOUT SYSTEM GDSII
SOURCE PATH "${CIR}"
SOURCE PRIMARY "${cell}"
SOURCE SYSTEM SPICE
LVS REPORT "${rep_work}"
INCLUDE "${RULES}"
EOF

  echo "==> Calibre LVS ${cell}"
  set +e
  (
    cd "$cell_work"
    "$CALIBRE_BIN" -lvs -hier -spice "$netlist" -nowait "$run_svrf" >"$log" 2>&1
  )
  local rc=$?
  set -e

  [[ -f "$rep_work" ]] && cp -f "$rep_work" "$lvsrep"
  [[ -f "$netlist" ]] && cp -f "$netlist" "$spice"

  local verdict="ERROR"
  # Calibre reports CORRECT / INCORRECT in the LVS summary
  if grep -qiE 'LVS\s+completed\.?\s*CORRECT|Comparison\s+Result\s*:\s*CORRECT|^CORRECT' "$lvsrep" 2>/dev/null \
    || grep -qiE 'LVS\s+completed\.?\s*CORRECT|Comparison\s+Result\s*:\s*CORRECT' "$log" 2>/dev/null; then
    verdict="PASS"
  elif grep -qiE 'LVS\s+completed\.?\s*INCORRECT|Comparison\s+Result\s*:\s*INCORRECT|^INCORRECT' "$lvsrep" 2>/dev/null \
    || grep -qiE 'LVS\s+completed\.?\s*INCORRECT|Comparison\s+Result\s*:\s*INCORRECT' "$log" 2>/dev/null; then
    verdict="FAIL"
  elif [[ "$rc" -ne 0 ]]; then
    verdict="ERROR"
  fi

  # Fallback: some Calibre builds only print "Incorrect" / "Correct" near end of .rep
  if [[ "$verdict" == "ERROR" && -f "$lvsrep" ]]; then
    if grep -qi 'incorrect' "$lvsrep"; then
      verdict="FAIL"
    elif grep -qi 'correct' "$lvsrep"; then
      verdict="PASS"
    fi
  fi

  local ok=1
  if [[ "$expect" == "pass" && "$verdict" == "PASS" ]]; then ok=0
  elif [[ "$expect" == "fail" && "$verdict" == "FAIL" ]]; then ok=0
  else ok=1
  fi

  {
    echo "Calibre LVS  cell=${cell}"
    echo "rules = transistor.calibre.svrf  (DEVICE MN(NMOS))"
    echo "schematic = nmos.cir  (.SUBCKT ${cell})"
    echo "result: ${verdict}  (expected ${expect})"
    echo "calibre_exit: ${rc}"
    if [[ -f "$lvsrep" ]]; then
      echo ""
      echo "--- ${lvsrep} (tail) ---"
      tail -80 "$lvsrep"
    elif [[ -f "$log" ]]; then
      echo ""
      echo "--- ${log} (tail) ---"
      tail -80 "$log"
    fi
  } >"$report"

  echo "    RESULT: ${verdict}  (expected ${expect})"
  if [[ "$verdict" == "ERROR" ]]; then
    echo "    see ${log}" >&2
    tail -30 "$log" >&2 || true
  fi
  return "$ok"
}

FAILS=0

if [[ "$WHICH" == "both" || "$WHICH" == "good" ]]; then
  run_one "NMOS_GOOD" "good" "pass" || FAILS=$((FAILS + 1))
fi
if [[ "$WHICH" == "both" || "$WHICH" == "bad" ]]; then
  run_one "NMOS_BAD" "bad" "fail" || FAILS=$((FAILS + 1))
fi

rm -f "$WORK"/*/CalibreRRLog.* 2>/dev/null || true

echo ""
if [[ "$FAILS" -eq 0 ]]; then
  echo "==> Calibre LVS demo OK (GOOD pass / BAD fail as expected)"
  exit 0
else
  echo "==> Calibre LVS demo: ${FAILS} unexpected result(s)" >&2
  exit 1
fi
