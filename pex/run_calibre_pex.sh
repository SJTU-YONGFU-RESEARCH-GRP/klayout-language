#!/usr/bin/env bash
# Run Calibre PEX on pex_demo.gds:
#   R — Calibre xRC (RESISTANCE SHEET)
#   C — Calibre LVS DEVICE CAP (overlap area)
# Does not generate GDS — run ./generate_layout.sh first.
#
# Usage:
#   ./run_calibre_pex.sh              # R/C GOOD/BAD
#   ./run_calibre_pex.sh --r          # resistance only
#   ./run_calibre_pex.sh --c          # capacitance only
#   ./run_calibre_pex.sh --good
#   ./run_calibre_pex.sh --bad
#   ./run_calibre_pex.sh --pex-only   # same as default (compat alias)
#   ./run_calibre_pex.sh --gen-only   # alias → ./generate_layout.sh
#   ./run_calibre_pex.sh --setup-help
#
# Env (same as drc/):
#   cp ../drc/calibre.env.example calibre.env   # or symlink ../drc/calibre.env
#   MGC_HOME / MGLS_LICENSE_FILE / CALIBRE

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GDS="${ROOT}/pex_demo.gds"
GEN_SH="${ROOT}/generate_layout.sh"
RULES_R="${ROOT}/m1_r.calibre.svrf"
RULES_C="${ROOT}/m1_c.calibre.svrf"
ENV_FILE="${ROOT}/calibre.env"
ENV_DRC="${ROOT}/../drc/calibre.env"
ENV_EXAMPLE="${ROOT}/../drc/calibre.env.example"
WORK="${ROOT}/.calibre_pex_run"

R_LIMIT="${R_LIMIT:-1.0}"
C_LIMIT_F="${C_LIMIT_F:-1e-15}"

WHICH="both"
KIND="both"   # r | c | both
SETUP_HELP=0

load_calibre_env() {
  if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    echo "==> Loaded ${ENV_FILE}"
  elif [[ -f "$ENV_DRC" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_DRC"
    echo "==> Loaded ${ENV_DRC}"
  fi
  # Prefer system python over Calibre's bin/python3 on PATH
  export PATH="/usr/bin:/bin:${MGC_HOME:+$MGC_HOME/bin:}${PATH}"
}

print_calibre_setup() {
  cat <<EOF
Calibre is not on PATH. Set it up like the DRC demo:

  cp ${ENV_EXAMPLE} ${ENV_FILE}
  \$EDITOR ${ENV_FILE}          # set MGC_HOME + MGLS_LICENSE_FILE
  ./run_calibre_pex.sh

Or reuse the DRC env:
  ln -sf ../drc/calibre.env ${ENV_FILE}
  ./run_calibre_pex.sh

Verify:
  \$MGC_HOME/bin/calibre -version
EOF
}

find_calibre() {
  if [[ -n "${CALIBRE:-}" && -x "${CALIBRE}" ]]; then
    printf '%s\n' "${CALIBRE}"
    return 0
  fi
  if command -v calibre >/dev/null 2>&1; then
    command -v calibre
    return 0
  fi
  local c
  for c in \
    "${MGC_HOME:-}/bin/calibre" \
    /opt/mentor/calibre/bin/calibre \
    /usr/local/mentor/calibre/bin/calibre
  do
    [[ -x "$c" ]] && { printf '%s\n' "$c"; return 0; }
  done
  return 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --good) WHICH="good" ;;
    --bad) WHICH="bad" ;;
    --r|--res|--resistance) KIND="r" ;;
    --c|--cap|--capacitance) KIND="c" ;;
    --pex-only) ;; # default is check-only
    --gen-only)
      exec "$GEN_SH"
      ;;
    --setup-help) SETUP_HELP=1 ;;
    -h|--help)
      sed -n '2,22p' "$0"
      exit 0
      ;;
    *) echo "Unknown option: $1 (try --setup-help)" >&2; exit 1 ;;
  esac
  shift
done

if [[ "$SETUP_HELP" -eq 1 ]]; then
  print_calibre_setup
  exit 0
fi

load_calibre_env

CALIBRE_BIN="$(find_calibre)" || {
  echo "ERROR: calibre not found." >&2
  print_calibre_setup >&2
  exit 1
}

[[ -f "$GDS" ]] || {
  echo "ERROR: missing ${GDS}" >&2
  echo "Run:  ./generate_layout.sh" >&2
  exit 1
}

echo "==> Calibre: $("$CALIBRE_BIN" -version 2>/dev/null | head -1 || echo "$CALIBRE_BIN")"
echo "==> License: ${MGLS_LICENSE_FILE:-unset}"

mkdir -p "$WORK"

# --- Parse total series R from xRC .pex model (educational 2-port chains) ---
parse_r_ohm() {
  local pex="$1"
  /usr/bin/python3 - "$pex" <<'PY'
import re, sys
text = open(sys.argv[1], encoding="utf-8", errors="replace").read()
vals = [float(m) for m in re.findall(r"(?m)^r\d+\s+\S+\s+\S+\s+([0-9.eE+-]+)", text)]
if not vals:
    print("NA")
else:
    print(f"{sum(vals):.6g}")
PY
}

parse_c_farad() {
  local sp="$1"
  /usr/bin/python3 - "$sp" <<'PY'
import re, sys
text = open(sys.argv[1], encoding="utf-8", errors="replace").read()
# X0 A B CAP c=9e-15
m = re.search(r"(?i)\bCAP\b[^\n]*\bc\s*=\s*([0-9.eE+-]+)", text)
if not m:
    m = re.search(r"(?i)\bc\s*=\s*([0-9.eE+-]+)", text)
print(m.group(1) if m else "NA")
PY
}

run_r() {
  local cell="$1"
  local tag="$2"
  local expect="$3"   # pass | fail
  local cell_work="${WORK}/${tag}_r"
  local report="${ROOT}/calibre_r_${tag}.txt"
  local spice="${ROOT}/calibre_r_${tag}.sp"
  local log="${ROOT}/calibre_r_${tag}.log"
  local pex_model="${spice}.pex"

  rm -rf "$cell_work"
  mkdir -p "$cell_work"
  local run_svrf="${cell_work}/run.svrf"
  local svdb="${cell_work}/svdb"
  local netlist="${cell_work}/out.sp"

  cat >"$run_svrf" <<EOF
// Auto-generated by run_calibre_pex.sh — do not edit
LAYOUT PATH "${GDS}"
LAYOUT PRIMARY "${cell}"
MASK SVDB DIRECTORY "${svdb}" XRC
PEX NETLIST "${netlist}" HSPICE LAYOUTNAMES
INCLUDE "${RULES_R}"
EOF

  echo "==> Calibre xRC-R ${cell}"
  set +e
  (
    cd "$cell_work"
    "$CALIBRE_BIN" -xrc -phdb -nowait "$run_svrf" >"${log}.phdb" 2>&1
    "$CALIBRE_BIN" -xrc -pdb -r -nowait "$run_svrf" >"${log}.pdb" 2>&1
    "$CALIBRE_BIN" -xrc -fmt -r -nowait "$run_svrf" >"${log}.fmt" 2>&1
  )
  set -e
  cat "${log}.phdb" "${log}.pdb" "${log}.fmt" >"$log" 2>/dev/null || true

  local rohms="NA"
  if [[ -f "${netlist}.pex" ]]; then
    cp -f "$netlist" "$spice"
    cp -f "${netlist}.pex" "$pex_model"
    local pxi
    pxi="$(ls "${netlist}".*.pxi 2>/dev/null | head -1 || true)"
    [[ -n "$pxi" && -f "$pxi" ]] && cp -f "$pxi" "${spice}.pxi"
    rohms="$(parse_r_ohm "$pex_model")"
  fi

  local verdict="ERROR"
  local ok=1
  if [[ "$rohms" != "NA" && -n "$rohms" ]]; then
    local ge
    ge="$(/usr/bin/awk -v r="$rohms" -v lim="$R_LIMIT" 'BEGIN{print (r+0 < lim+0) ? 1 : 0}')"
    if [[ "$ge" -eq 1 ]]; then verdict="PASS"; else verdict="FAIL"; fi
    if [[ "$expect" == "pass" && "$verdict" == "PASS" ]]; then ok=0
    elif [[ "$expect" == "fail" && "$verdict" == "FAIL" ]]; then ok=0
    else ok=1
    fi
  fi

  {
    echo "Calibre xRC  cell=${cell}"
    echo "sheet_r = 0.08 ohm/sq  (RESISTANCE SHEET M1)"
    echo "R_AB ≈ ${rohms} ohm  (sum of .pex resistors)"
    echo "limit = ${R_LIMIT} ohm  (PASS if R < limit)"
    echo "result: ${verdict}  (expected ${expect})"
    if [[ -f "$pex_model" ]]; then
      echo ""
      echo "--- ${pex_model} ---"
      cat "$pex_model"
    fi
  } >"$report"

  echo "    RESULT: ${verdict}  R≈${rohms} ohm  (limit ${R_LIMIT})"
  return "$ok"
}

run_c() {
  local cell="$1"
  local tag="$2"
  local expect="$3"
  local cell_work="${WORK}/${tag}_c"
  local report="${ROOT}/calibre_c_${tag}.txt"
  local spice="${ROOT}/calibre_c_${tag}.sp"
  local log="${ROOT}/calibre_c_${tag}.log"

  rm -rf "$cell_work"
  mkdir -p "$cell_work"
  local run_svrf="${cell_work}/run.svrf"
  local netlist="${cell_work}/out.sp"
  local lvsrep="${cell_work}/lvs.rep"

  cat >"$run_svrf" <<EOF
// Auto-generated by run_calibre_pex.sh — do not edit
LAYOUT PATH "${GDS}"
LAYOUT PRIMARY "${cell}"
LVS REPORT "${lvsrep}"
INCLUDE "${RULES_C}"
EOF

  echo "==> Calibre DEVICE-C ${cell}"
  set +e
  (
    cd "$cell_work"
    "$CALIBRE_BIN" -lvs -hier -spice "$netlist" -nowait "$run_svrf" >"$log" 2>&1
  )
  set -e

  local cfarad="NA"
  if [[ -f "$netlist" ]]; then
    cp -f "$netlist" "$spice"
    cfarad="$(parse_c_farad "$spice")"
  fi

  local verdict="ERROR"
  local ok=1
  if [[ "$cfarad" != "NA" && -n "$cfarad" ]]; then
    local ge
    ge="$(/usr/bin/awk -v c="$cfarad" -v lim="$C_LIMIT_F" 'BEGIN{print (c+0 >= lim+0) ? 1 : 0}')"
    if [[ "$ge" -eq 1 ]]; then verdict="PASS"; else verdict="FAIL"; fi
    if [[ "$expect" == "pass" && "$verdict" == "PASS" ]]; then ok=0
    elif [[ "$expect" == "fail" && "$verdict" == "FAIL" ]]; then ok=0
    else ok=1
    fi
  fi

  local cff="NA"
  if [[ "$cfarad" != "NA" ]]; then
    cff="$(/usr/bin/awk -v c="$cfarad" 'BEGIN{printf "%.4g", c*1e15}')"
  fi

  {
    echo "Calibre DEVICE CAP  cell=${cell}"
    echo "area_cap = 1e-15 F/um^2  (C = AREA(M1 AND M2) * 1e-3 fF)"
    echo "C = ${cfarad} F  (${cff} fF)"
    echo "limit = ${C_LIMIT_F} F  (PASS if C >= limit)"
    echo "result: ${verdict}  (expected ${expect})"
    if [[ -f "$spice" ]]; then
      echo ""
      echo "--- ${spice} ---"
      cat "$spice"
    fi
  } >"$report"

  echo "    RESULT: ${verdict}  C=${cff} fF  (limit $(/usr/bin/awk -v l="$C_LIMIT_F" 'BEGIN{printf "%.4g", l*1e15}') fF)"
  return "$ok"
}

FAILS=0

if [[ "$KIND" == "both" || "$KIND" == "r" ]]; then
  if [[ "$WHICH" == "both" || "$WHICH" == "good" ]]; then
    run_r "R_GOOD" "good" "pass" || FAILS=$((FAILS + 1))
  fi
  if [[ "$WHICH" == "both" || "$WHICH" == "bad" ]]; then
    run_r "R_BAD" "bad" "fail" || FAILS=$((FAILS + 1))
  fi
fi

if [[ "$KIND" == "both" || "$KIND" == "c" ]]; then
  if [[ "$WHICH" == "both" || "$WHICH" == "good" ]]; then
    run_c "C_GOOD" "good" "pass" || FAILS=$((FAILS + 1))
  fi
  if [[ "$WHICH" == "both" || "$WHICH" == "bad" ]]; then
    run_c "C_BAD" "bad" "fail" || FAILS=$((FAILS + 1))
  fi
fi

# Cleanup turbu junk
rm -f "$WORK"/*/CalibreRRLog.* 2>/dev/null || true

echo ""
if [[ "$FAILS" -eq 0 ]]; then
  echo "==> Calibre PEX demo OK (GOOD pass / BAD fail as expected)"
  exit 0
else
  echo "==> Calibre PEX demo: ${FAILS} unexpected result(s)" >&2
  exit 1
fi
