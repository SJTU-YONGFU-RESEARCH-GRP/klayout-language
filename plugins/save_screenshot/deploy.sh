#!/usr/bin/env bash
# Deploy the Save Layout Screenshot macro into the KLayout user folders.
#
# Usage:
#   ./deploy.sh              # install
#   ./deploy.sh --uninstall  # remove
#   ./deploy.sh --dry-run
#   ./deploy.sh --dest DIR

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_LYM="${SCRIPT_DIR}/save_screenshot.lym"
SOURCE_PY="${SCRIPT_DIR}/save_screenshot.py"
MACRO_NAME="save_screenshot.lym"
MODULE_NAME="save_screenshot.py"
CONFIG_NAME="save_screenshot_config.py"
# plugins/save_screenshot -> repo root
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
SCREENSHOT_DIR="${PROJECT_ROOT}/screenshots"

ACTION="install"
DRY_RUN=0
DEST_DIR=""
PYTHON_DIR=""

usage() {
  cat <<'EOF'
Deploy Save Layout Screenshot to KLayout.

Installs:
  - save_screenshot.lym         -> <klayout>/pymacros/
  - save_screenshot.py          -> <klayout>/python/
  - save_screenshot_config.py   -> <klayout>/python/  (default save dir)

Default screenshots go to: <repo>/screenshots
Override at runtime with KLAYOUT_SCREENSHOT_DIR.

Options:
  -d, --dest DIR    Target pymacros directory (default: auto-detect)
  -u, --uninstall   Remove the installed macro and module
  -n, --dry-run     Print actions without copying/removing
  -h, --help        Show this help

Examples:
  ./deploy.sh
  ./deploy.sh --dest "$HOME/.klayout/pymacros"
  ./deploy.sh --uninstall
EOF
}

log()  { printf '==> %s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

run() {
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf '[dry-run] %s\n' "$*"
  else
    "$@"
  fi
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -d|--dest)
      [[ $# -ge 2 ]] || die "--dest requires an argument"
      DEST_DIR="$2"
      shift 2
      ;;
    -u|--uninstall)
      ACTION="uninstall"
      shift
      ;;
    -n|--dry-run)
      DRY_RUN=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "Unknown option: $1 (use --help)"
      ;;
  esac
done

detect_klayout_home() {
  if [[ -n "${KLAYOUT_HOME:-}" ]]; then
    printf '%s' "${KLAYOUT_HOME%/}"
    return 0
  fi

  case "$(uname -s)" in
    Linux*)
      printf '%s/.klayout' "$HOME"
      ;;
    Darwin*)
      local mac_pref="${HOME}/Library/Preferences/KLayout"
      local unix_pref="${HOME}/.klayout"
      if [[ -d "$mac_pref" || ! -d "$unix_pref" ]]; then
        printf '%s' "$mac_pref"
      else
        printf '%s' "$unix_pref"
      fi
      ;;
    MINGW*|MSYS*|CYGWIN*)
      printf '%s/KLayout' "${USERPROFILE:-$HOME}"
      ;;
    *)
      warn "Unknown OS $(uname -s); using ~/.klayout"
      printf '%s/.klayout' "$HOME"
      ;;
  esac
}

write_config() {
  local target_config="$1"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf '[dry-run] write %s (DEFAULT_SAVE_DIR=%s)\n' "$target_config" "$SCREENSHOT_DIR"
    return 0
  fi
  cat >"$target_config" <<EOF
# Auto-generated by deploy.sh — default screenshot output directory
DEFAULT_SAVE_DIR = r"${SCREENSHOT_DIR}"
EOF
}

install_files() {
  [[ -f "$SOURCE_LYM" ]] || die "Source macro not found: $SOURCE_LYM"
  [[ -f "$SOURCE_PY" ]] || die "Source module not found: $SOURCE_PY"

  local target_lym="${DEST_DIR}/${MACRO_NAME}"
  local target_py="${PYTHON_DIR}/${MODULE_NAME}"
  local target_config="${PYTHON_DIR}/${CONFIG_NAME}"

  log "Source macro: ${SOURCE_LYM}"
  log "Source module: ${SOURCE_PY}"
  log "Destination macro: ${target_lym}"
  log "Destination module: ${target_py}"
  log "Default save dir: ${SCREENSHOT_DIR}"

  run mkdir -p "$DEST_DIR" "$PYTHON_DIR" "$SCREENSHOT_DIR"

  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf '[dry-run] cp "%s" "%s"\n' "$SOURCE_LYM" "$target_lym"
    printf '[dry-run] cp "%s" "%s"\n' "$SOURCE_PY" "$target_py"
  else
    cp "$SOURCE_LYM" "$target_lym"
    cp "$SOURCE_PY" "$target_py"
  fi
  write_config "$target_config"

  log "Installed ${MACRO_NAME}, ${MODULE_NAME}, and ${CONFIG_NAME}"
  log "Restart KLayout to use: Screenshot → Save Layout Screenshot"
}

uninstall_files() {
  local target_lym="${DEST_DIR}/${MACRO_NAME}"
  local target_py="${PYTHON_DIR}/${MODULE_NAME}"
  local target_config="${PYTHON_DIR}/${CONFIG_NAME}"
  local missing=1

  if [[ -e "$target_lym" ]]; then
    missing=0
    log "Removing: ${target_lym}"
    run rm -f "$target_lym"
  else
    warn "Macro not installed: ${target_lym}"
  fi

  if [[ -e "$target_py" ]]; then
    missing=0
    log "Removing: ${target_py}"
    run rm -f "$target_py"
  else
    warn "Module not installed: ${target_py}"
  fi

  if [[ -e "$target_config" ]]; then
    missing=0
    log "Removing: ${target_config}"
    run rm -f "$target_config"
  fi

  if [[ "$missing" -eq 0 ]]; then
    log "Uninstalled save_screenshot"
  fi
}

main() {
  local klayout_home
  klayout_home="$(detect_klayout_home)"

  if [[ -z "$DEST_DIR" ]]; then
    DEST_DIR="${klayout_home}/pymacros"
  fi
  PYTHON_DIR="$(cd "$(dirname "$DEST_DIR")" && pwd)/python"

  log "Action: ${ACTION}"
  log "KLayout home: ${klayout_home}"
  log "Target pymacros: ${DEST_DIR}"
  log "Target python: ${PYTHON_DIR}"

  if [[ "$ACTION" == "install" ]]; then
    install_files
  else
    uninstall_files
  fi

  log "Done."
}

main "$@"
